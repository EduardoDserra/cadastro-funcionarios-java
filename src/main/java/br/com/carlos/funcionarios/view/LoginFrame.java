    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        final String email = txtEmail.getText();
        final String senha = new String(txtSenha.getPassword());

        btnEntrar.setEnabled(false);
        btnCriarConta.setEnabled(false);

        new SwingWorker<Usuario, Void>() {

            @Override
            protected Usuario doInBackground() throws Exception {
                return loginController.autenticar(email, senha);
            }

            @Override
            protected void done() {
                try {
                    Usuario usuario = get();

                    FuncionarioFrame tela = new FuncionarioFrame();
                    tela.setVisible(true);
                    LoginFrame.this.dispose();

                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();

                    JOptionPane.showMessageDialog(
                            LoginFrame.this,
                            "A operação foi interrompida.",
                            "Erro",
                            JOptionPane.ERROR_MESSAGE
                    );

                } catch (ExecutionException e) {
                    Throwable causa = e.getCause();

                    String mensagem = causa instanceof IllegalArgumentException
                            ? causa.getMessage()
                            : "Não foi possível entrar. Verifique a conexão com o banco.";

                    JOptionPane.showMessageDialog(
                            LoginFrame.this,
                            mensagem,
                            "Não foi possível entrar",
                            JOptionPane.ERROR_MESSAGE
                    );

                } finally {
                    txtSenha.setText("");
                    btnEntrar.setEnabled(true);
                    btnCriarConta.setEnabled(true);
                }
            }
        }.execute();
    }//GEN-LAST:event_btnEntrarActionPerformed

