    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        final String nome = txtNome.getText();
        final String email = txtEmail.getText();
        final String senha = new String(txtSenha.getPassword());
        final String confirmarSenha
                = new String(txtConfirmarSenha.getPassword());

        if (!senha.equals(confirmarSenha)) {
            JOptionPane.showMessageDialog(
                    this,
                    "As senhas não coincidem. Digite novamente.",
                    "Verifique os dados",
                    JOptionPane.WARNING_MESSAGE
            );

            txtConfirmarSenha.setText("");
            txtConfirmarSenha.requestFocusInWindow();
            return;
        }

        btnCadastrar.setEnabled(false);
        btnCancelar.setEnabled(false);

        new SwingWorker<Void, Void>() {

            @Override
            protected Void doInBackground() throws Exception {
                usuarioController.cadastrar(nome, email, senha);
                return null;
            }

            @Override
            protected void done() {
                try {
                    get();

                    JOptionPane.showMessageDialog(
                            CadastroUsuarioFrame.this,
                            "Conta criada com sucesso! Faça login para continuar."
                    );

                    dispose();

                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();

                    JOptionPane.showMessageDialog(
                            CadastroUsuarioFrame.this,
                            "A operação foi interrompida.",
                            "Erro",
                            JOptionPane.ERROR_MESSAGE
                    );

                } catch (ExecutionException e) {
                    Throwable causa = e.getCause();

                    String mensagem = causa instanceof IllegalArgumentException
                            ? causa.getMessage()
                            : "Não foi possível cadastrar. "
                            + "Verifique a conexão com o banco.";

                    JOptionPane.showMessageDialog(
                            CadastroUsuarioFrame.this,
                            mensagem,
                            "Não foi possível cadastrar",
                            JOptionPane.ERROR_MESSAGE
                    );

                } finally {
                    txtSenha.setText("");
                    txtConfirmarSenha.setText("");
                    btnCadastrar.setEnabled(true);
                    btnCancelar.setEnabled(true);
                }
            }
        }.execute();
    }//GEN-LAST:event_btnCadastrarActionPerformed

